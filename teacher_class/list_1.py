# 리스트 이론 2
arr = [10, 10, 10, 10, 10, 10]  # 이렇게 채우고 싶다

# 1. 첫번째 방법 append
arr = []
for _ in range(6):
    arr.append(10)

# 2. 두번째 방법 인덱싱
arr = [0] * 6   # pythonic 한 방법
for i in range(6):
    arr[i] = 10

# 결론 : 두 가지 방법 다 익혀야함. 능숙도 올리기

