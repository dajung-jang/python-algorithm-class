# lev: 지금 몇뻔째 자리를 채우고 있는지(depth)
def KFC(lev):
    if lev == 2:
        print(*path)
        return

    for i in range(3):
        # 이미 쓴 원소면 넘어가겠다(중복 안되게)
        if used[i] == 1: continue
        # 지금 돌고 있는건 사용했다고 표시
        used[i] = 1
